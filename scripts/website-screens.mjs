#!/usr/bin/env node
/**
 * Builds the website's screenshot ladder from captures of the real app. Developer tool, not shipped.
 *
 *   node scripts/website-screens.mjs <captures-folder>
 *
 * The folder holds one PNG per screen in SCREENS, captured from the running app at 2x or more with the window at the
 * listed size (a 1280 x 800 window captured at 2x is 2560 x 1600). Each capture becomes a width ladder in AVIF and
 * WebP under website/assets/screens/, plus a phone crop ladder cut from the app-pixel rectangle in `phone`, so phones
 * show a legible part of the window instead of the whole window at a quarter of its size. The script rewrites
 * website/app/screens.js with the sizes the page markup reads, and deletes the previous files of every screen it builds.
 *
 * Needs ImageMagick 7 (`magick`) with its AVIF (libheif) and WebP coders.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = path.join(ROOT, 'website', 'assets', 'screens')
const MODULE_PATH = path.join(ROOT, 'website', 'app', 'screens.js')

/** Phone crops are served at about the width of a phone's content column at 1x, 2x, and 3x. */
const PHONE_WIDTHS = [400, 760, 1140]

const SCREENS = [
  { name: 'run', window: [1120, 720], widths: [640, 960, 1280, 1600, 2240], phone: [208, 40, 564, 438] },
  { name: 'batch', window: [1280, 800], widths: [640, 960, 1440, 2048, 2560], phone: [962, 162, 306, 404] },
  { name: 'editor', window: [1280, 800], widths: [640, 960, 1440, 2048, 2560], phone: [208, 40, 772, 760] },
  { name: 'player', window: [1280, 800], widths: [640, 960, 1440, 2048, 2560], phone: [208, 40, 732, 760] }
]

const ENCODERS = {
  avif: ['-quality', '60', '-define', 'heic:chroma=444', '-define', 'heic:speed=4'],
  webp: ['-quality', '84', '-define', 'webp:method=6', '-define', 'webp:use-sharp-yuv=true']
}

function fail(message)
{
  console.error(message)
  process.exit(1)
}

function magick(args)
{
  const result = spawnSync('magick', args, { encoding: 'utf8' })
  if (result.error) fail(`Could not run ImageMagick: ${result.error.message}`)
  if (result.status !== 0) fail(`magick ${args.join(' ')}\n${result.stderr}`)
  return result.stdout
}

function dimensions(file)
{
  const [w, h] = magick([file, '-format', '%w %h', 'info:']).trim().split(' ').map(Number)
  return { w, h }
}

/** The capture's pixels per app pixel, which must be a whole number of at least 2 on both axes. */
function captureScale(screen, size)
{
  const scale = size.w / screen.window[0]
  if (!Number.isInteger(scale) || scale < 2 || size.h !== screen.window[1] * scale)
  {
    fail(`${screen.name}.png is ${size.w} x ${size.h}; it must be the ${screen.window.join(' x ')} window captured at 2x or more`)
  }
  return scale
}

/** Writes every width of one image in both formats and returns the widths written, smallest first. */
function ladder(source, crop, widths, stem)
{
  const written = []
  for (const width of widths)
  {
    for (const [ext, options] of Object.entries(ENCODERS))
    {
      magick([source, ...crop, '-resize', `${width}x`, '-strip', ...options, path.join(OUT_DIR, `${stem}-${width}.${ext}`)])
    }
    written.push(width)
  }
  return written
}

function removePrevious(name)
{
  const own = new RegExp(`^${name}-(phone-)?\\d+\\.(avif|webp)$`)
  for (const file of readdirSync(OUT_DIR))
  {
    if (own.test(file) || file === `${name}.webp`) rmSync(path.join(OUT_DIR, file))
  }
}

function moduleSource(built)
{
  const entries = built.map((s) => `    ${s.name}: { width: ${s.width}, height: ${s.height}, widths: [${s.widths.join(', ')}], phone: { width: ${s.phone.width}, height: ${s.phone.height}, widths: [${s.phone.widths.join(', ')}] } },`)
  return [
    '/** Generated by scripts/website-screens.mjs; rerun the script after new captures instead of editing this file. */',
    'export const SCREENS = {',
    ...entries,
    '};',
    ''
  ].join('\n')
}

const capturesDir = process.argv[2]
if (!capturesDir) fail('Usage: node scripts/website-screens.mjs <captures-folder>')

const built = []
for (const screen of SCREENS)
{
  const source = path.resolve(capturesDir, `${screen.name}.png`)
  if (!existsSync(source)) fail(`Missing capture ${source}`)
  const scale = captureScale(screen, dimensions(source))
  const full = screen.window[0] * scale
  const [x, y, w, h] = screen.phone.map((v) => v * scale)
  const phoneWidths = [...new Set(PHONE_WIDTHS.map((width) => Math.min(width, w)))]

  removePrevious(screen.name)
  const widths = ladder(source, [], screen.widths.filter((width) => width <= full), screen.name)
  const phone = ladder(source, ['-crop', `${w}x${h}+${x}+${y}`, '+repage'], phoneWidths, `${screen.name}-phone`)
  const top = widths[widths.length - 1]
  const phoneTop = phone[phone.length - 1]
  built.push({
    name: screen.name,
    width: top,
    height: Math.round(top * screen.window[1] / screen.window[0]),
    widths,
    phone: { width: phoneTop, height: Math.round(phoneTop * h / w), widths: phone }
  })
  console.log(`${screen.name}: ${widths.join(', ')} and phone ${phone.join(', ')} from a ${scale}x capture`)
}

writeFileSync(MODULE_PATH, moduleSource(built))
console.log(`Wrote ${path.relative(ROOT, MODULE_PATH)}`)
